export const STRINGS: Record<Lang, Record<StringKey, string>> = { id, en }

/** The visitor's first preferred language decides; Indonesian codes are `id` (and legacy `in`). */
export function detectLang(langs: readonly string[]): Lang {
  const first = (langs[0] ?? '').toLowerCase()
  return first.startsWith('id') || first.startsWith('in') ? 'id' : 'en'
}

export function t(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const s = STRINGS[lang][key]
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s
}
